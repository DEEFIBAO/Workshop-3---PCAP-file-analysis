"""Provided helper: safe PCAP / PCAPNG *file framing* (no protocol decoding).

Students do not edit this file. It turns a capture file into raw frames:

    reader = CaptureReader("capture.pcap")
    for frame in reader.frames():
        frame["number"], frame["timestamp"], frame["link_type"], frame["data"] ...

Decoding the bytes inside each frame (Ethernet / IP / TCP ...) is the job of
``engine/pcap_reader.py``.

Safety: the file is only ever *parsed* (never executed), every length field is
range-checked, and a damaged file stops the iteration with a warning instead of
raising or allocating huge buffers.
"""
from __future__ import annotations

import os
import struct
from typing import Dict, Iterator, List, Optional

MAX_RECORD_BYTES = 1 << 20          # refuse single frames larger than 1 MiB
PCAP_MAGICS = {
    b"\xd4\xc3\xb2\xa1": ("<", 1e-6), b"\xa1\xb2\xc3\xd4": (">", 1e-6),   # microsecond
    b"\x4d\x3c\xb2\xa1": ("<", 1e-9), b"\xa1\xb2\x3c\x4d": (">", 1e-9),   # nanosecond
}
PCAPNG_MAGIC = b"\x0a\x0d\x0d\x0a"

LINK_TYPE_NAMES = {
    0: "NULL (BSD loopback)", 1: "Ethernet", 12: "Raw IP", 101: "Raw IP",
    113: "Linux cooked (SLL)", 228: "Raw IPv4", 229: "Raw IPv6", 276: "Linux cooked v2 (SLL2)",
}


class PcapFormatError(ValueError):
    """Raised when the file is not a PCAP/PCAPNG capture at all."""


class CaptureReader:
    """Iterate raw frames from a .pcap or .pcapng file."""

    def __init__(self, path: str):
        self.path = path
        self.file_size: Optional[int] = None
        self.format: Optional[str] = None            # "pcap" or "pcapng"
        self.snaplen: Optional[int] = None
        self.link_types: Dict[int, str] = {}
        self.warnings: List[str] = []
        self.file_truncated = False
        try:
            self.file_size = os.path.getsize(path)
        except OSError:
            self.file_size = None
        with open(path, "rb") as handle:
            head = handle.read(4)
        if head in PCAP_MAGICS:
            self.format = "pcap"
        elif head == PCAPNG_MAGIC:
            self.format = "pcapng"
        else:
            raise PcapFormatError("Not a PCAP or PCAPNG file (unrecognised file header).")

    def frames(self) -> Iterator[dict]:
        with open(self.path, "rb") as handle:
            if self.format == "pcap":
                yield from self._pcap(handle)
            else:
                yield from self._pcapng(handle)

    # ------------------------------------------------------------------ pcap
    def _pcap(self, handle) -> Iterator[dict]:
        header = handle.read(24)
        if len(header) < 24:
            self.file_truncated = True
            self.warnings.append("PCAP global header is incomplete; no packets could be read.")
            return
        endian, resolution = PCAP_MAGICS[header[:4]]
        _, _, _, _, snaplen, network = struct.unpack(endian + "HHiIII", header[4:24])
        self.snaplen = snaplen or None
        link_type = network & 0x0FFFFFFF
        self.link_types[link_type] = LINK_TYPE_NAMES.get(link_type, f"Unsupported ({link_type})")
        number = 0
        while True:
            record = handle.read(16)
            if not record:
                return
            if len(record) < 16:
                self.file_truncated = True
                self.warnings.append("Capture ends in the middle of a packet header (file truncated).")
                return
            seconds, fraction, caplen, origlen = struct.unpack(endian + "IIII", record)
            if caplen > MAX_RECORD_BYTES:
                self.file_truncated = True
                self.warnings.append(f"Implausible captured length ({caplen}) at packet {number + 1}; stopped reading.")
                return
            data = handle.read(caplen)
            if len(data) < caplen:
                self.file_truncated = True
                self.warnings.append("Capture ends in the middle of a packet (file truncated).")
                return
            number += 1
            yield {"number": number, "timestamp": seconds + fraction * resolution,
                   "link_type": link_type, "data": data, "original_length": origlen}

    # ---------------------------------------------------------------- pcapng
    def _pcapng(self, handle) -> Iterator[dict]:
        endian = "<"
        interfaces: List[dict] = []
        number = 0
        while True:
            head = handle.read(8)
            if not head:
                return
            if len(head) < 8:
                self.file_truncated = True
                self.warnings.append("PCAPNG ends in the middle of a block header.")
                return
            block_type_raw = head[:4]
            if block_type_raw == PCAPNG_MAGIC:                       # section header: learn endianness
                rest_peek = handle.read(4)
                if len(rest_peek) < 4:
                    self.file_truncated = True
                    return
                endian = "<" if rest_peek == b"\x4d\x3c\x2b\x1a" else ">"
                total_len = struct.unpack(endian + "I", head[4:8])[0]
                body = rest_peek + handle.read(max(total_len - 12, 0))
                body_len = len(body)
                interfaces = []
                if total_len < 28 or body_len < total_len - 8:
                    self.file_truncated = True
                    return
                continue
            block_type, total_len = struct.unpack(endian + "II", head)
            if total_len < 12 or total_len % 4 or total_len > MAX_RECORD_BYTES + 64:
                self.file_truncated = True
                self.warnings.append(f"Invalid PCAPNG block length ({total_len}); stopped reading.")
                return
            body = handle.read(total_len - 8)
            if len(body) < total_len - 8:
                self.file_truncated = True
                self.warnings.append("PCAPNG ends in the middle of a block (file truncated).")
                return
            payload = body[:-4]
            if block_type == 1 and len(payload) >= 8:                     # Interface Description Block
                link, _, snap = struct.unpack(endian + "HHI", payload[:8])
                interfaces.append({"link": link, "res": self._tsresol(payload[8:], endian), "snap": snap})
                self.link_types[link] = LINK_TYPE_NAMES.get(link, f"Unsupported ({link})")
                self.snaplen = snap or self.snaplen
            elif block_type == 6 and len(payload) >= 20:                   # Enhanced Packet Block
                if_id, ts_hi, ts_lo, caplen, origlen = struct.unpack(endian + "IIIII", payload[:20])
                if if_id >= len(interfaces) or caplen > len(payload) - 20:
                    self.warnings.append("Skipped a PCAPNG packet with inconsistent lengths.")
                    continue
                iface = interfaces[if_id]
                number += 1
                yield {"number": number, "timestamp": ((ts_hi << 32) | ts_lo) * iface["res"],
                       "link_type": iface["link"], "data": payload[20:20 + caplen], "original_length": origlen}
            elif block_type == 3 and interfaces and len(payload) >= 4:      # Simple Packet Block (no timestamp)
                origlen = struct.unpack(endian + "I", payload[:4])[0]
                data = payload[4:4 + min(origlen, interfaces[0]["snap"] or origlen)]
                number += 1
                yield {"number": number, "timestamp": None, "link_type": interfaces[0]["link"],
                       "data": data, "original_length": origlen}

    @staticmethod
    def _tsresol(options: bytes, endian: str) -> float:
        offset = 0
        while offset + 4 <= len(options):
            code, length = struct.unpack(endian + "HH", options[offset:offset + 4])
            if code == 0:
                break
            if code == 9 and length >= 1 and offset + 5 <= len(options):
                value = options[offset + 4]
                return 2.0 ** -(value & 0x7F) if value & 0x80 else 10.0 ** -(value & 0x7F)
            offset += 4 + ((length + 3) // 4) * 4
        return 1e-6
